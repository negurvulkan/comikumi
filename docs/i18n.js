  function detectLocale() {
    try {
      var stored = window.localStorage.getItem(STORAGE_KEY);
      if (stored && SUPPORTED.indexOf(stored) !== -1) return stored;
    } catch (e) {
      /* localStorage unavailable (private mode, etc.) — fall through */
    }
    var nav = (navigator.language || "en").slice(0, 2).toLowerCase();
    return SUPPORTED.indexOf(nav) !== -1 ? nav : "en";
  }

  function applyLocale(locale) {
    var dict = translations[locale] || translations.en;
    document.documentElement.setAttribute("lang", locale);

    var titleEl = document.querySelector('[data-i18n="meta.title"]');
    if (titleEl && dict["meta.title"]) document.title = dict["meta.title"];

    var descEl = document.querySelector('meta[name="description"]');
    if (descEl && dict["meta.description"]) descEl.setAttribute("content", dict["meta.description"]);

    var nodes = document.querySelectorAll("[data-i18n]");
    for (var i = 0; i < nodes.length; i++) {
      var key = nodes[i].getAttribute("data-i18n");
      if (dict[key]) nodes[i].textContent = dict[key];
    }

    var select = document.getElementById("langSelect");
    if (select) select.value = locale;
  }

  function saveLocale(locale) {
    try {
      window.localStorage.setItem(STORAGE_KEY, locale);
    } catch (e) {
      /* ignore */
    }
  }

  document.addEventListener("DOMContentLoaded", function () {
    var locale = detectLocale();
    applyLocale(locale);

    var select = document.getElementById("langSelect");
    if (select) {
      select.addEventListener("change", function () {
        var next = select.value;
        saveLocale(next);
        applyLocale(next);
      });
    }

    var navToggle = document.getElementById("navToggle");
    var mainNav = document.getElementById("mainNav");
    if (navToggle && mainNav) {
      navToggle.addEventListener("click", function () {
        var isOpen = mainNav.classList.toggle("open");
        navToggle.setAttribute("aria-expanded", isOpen ? "true" : "false");
      });
      mainNav.addEventListener("click", function (e) {
        if (e.target.tagName === "A") {
          mainNav.classList.remove("open");
          navToggle.setAttribute("aria-expanded", "false");
        }
      });
    }
  });
